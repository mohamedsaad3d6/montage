"""Music step: a background bed for an episode, free only.

    <core python> -m monteer.music.music --seconds 70 --out <project>/work/assets/music/bed.wav
        [--prompt "..."] [--seed 42] [--steps 27] [--attempts 2] [--max-minutes 25] [--code-only]

1. ACE-Step v1 (Apache 2.0, runs locally on the CPU) makes the bed. Each take is checked for vocals or words
   (music/vocal_check.py: sound classifier + speech recognition); a take with any is rejected and the next
   seed is tried, up to --attempts takes.
2. Fallback: the code-generated bed (music/code_bed.py, no AI, no licence) when ACE-Step is missing, fails,
   runs longer than --max-minutes, gives a broken file, or every take had vocals.
3. Finishing, the same for both: cut to the exact length, 0.5 s fade-in, 2 s fade-out, 48 kHz stereo 16-bit,
   loudness -20 LUFS with peaks at or below -1 dBFS. Setting the level under the voice is the mixer's job.
Writes <out>.json next to the wav: which generator and why, every take with its time and check, loudness, licence.
"""
import argparse
import json
import os
import re
import signal
import subprocess
import sys
import time
from pathlib import Path

from ..core import heavy
from ..core.io import save_json
from ..core.paths import ACE_STEP, CACHE, ENGINE, FFMPEG, ML_PY

ACE_PY = ML_PY
ACE_CKPT = ACE_STEP
HERE = Path(__file__).resolve().parent
FF = str(FFMPEG)
TARGET_LUFS = -20.0
DEFAULT_PROMPT = ("dark ambient, cinematic, tense, documentary underscore, instrumental, low drone, "
                  "deep pulsing synth bass, sparse piano, slow tempo, 80 bpm, suspense, minor key, no vocals")
LICENCE = {"ace-step": "AI-generated with ACE-Step v1-3.5B (Apache 2.0). Free for commercial use; the model card asks "
                       "to disclose AI involvement and not to present it as human-made.",
           "code-bed": "Code-generated by monteer/music/code_bed.py (our own synthesis, no samples, no AI): "
                       "no licence needed."}


def ace_env():
    """keep ACE-Step's caches inside monteer_data/cache and never touch the network (the model is local)"""
    env = dict(os.environ)
    env.update(HF_HOME=str(CACHE / "hf"), HF_HUB_OFFLINE="1", TRANSFORMERS_OFFLINE="1", HF_HUB_DISABLE_TELEMETRY="1",
               XDG_CACHE_HOME=str(CACHE / "xdg"), TORCH_HOME=str(CACHE / "torch"), PYTHONPATH=str(ENGINE), PYTHONDONTWRITEBYTECODE="1")
    return env


def run_limited(cmd, timeout_s, env=None):
    """run a child process; kill its whole process group if it runs past timeout_s. -> (returncode|None, stdout, stderr)"""
    p = subprocess.Popen([str(c) for c in cmd], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                         env=env, start_new_session=True)
    try:
        out, err = p.communicate(timeout=timeout_s)
        return p.returncode, out, err
    except subprocess.TimeoutExpired:
        os.killpg(p.pid, signal.SIGKILL)
        out, err = p.communicate()
        return None, out, err


def last_json(text):
    for line in reversed(text.strip().splitlines()):
        if line.startswith("{"):
            return json.loads(line)
    return None


def measure(path):
    """integrated loudness (LUFS), true peak (dBFS) and length (s)"""
    err = subprocess.run([FF, "-hide_banner", "-i", str(path), "-af", "ebur128=peak=true", "-f", "null", "-"],
                         capture_output=True, text=True).stderr
    s = err[err.rfind("Summary:"):]
    i = re.search(r"I:\s+(-?[\d.]+|-inf)", s).group(1)
    pk = re.search(r"Peak:\s+(-?[\d.]+|-inf)", s).group(1)
    dur = re.findall(r"time=(\d+):(\d+):([\d.]+)", err)
    h, m, sec = dur[-1] if dur else (0, 0, 0)
    return float(i), float(pk), int(h) * 3600 + int(m) * 60 + float(sec)


def finish(src, out, seconds):
    lufs, peak, _ = measure(src)
    gain = TARGET_LUFS - lufs
    if peak + gain > -1.0:
        gain = -1.0 - peak
    fo = min(2.0, seconds / 6)
    subprocess.run([FF, "-v", "error", "-y", "-i", str(src), "-af",
                    f"atrim=0:{seconds:.4f},asetpts=PTS-STARTPTS,aresample=48000,volume={gain:.2f}dB,"
                    f"afade=t=in:d=0.5,afade=t=out:st={seconds - fo:.4f}:d={fo:.4f},apad=whole_dur={seconds:.4f}",
                    "-ac", "2", "-ar", "48000", "-c:a", "pcm_s16le", str(out)], check=True)
    lufs2, peak2, dur2 = measure(out)
    return {"source_lufs": lufs, "gain_db": round(gain, 2), "lufs": lufs2, "true_peak_dbfs": peak2, "seconds": round(dur2, 3)}


def try_ace(a, tmp, log):
    """ACE-Step takes until one passes the vocals check -> path of the clean raw take, or None"""
    if not (ACE_PY.exists() and ACE_CKPT.exists()):
        log["fallback_reason"] = "ACE-Step environment or model not found"
        return None
    deadline = time.time() + a.max_minutes * 60
    need = 60.0
    for k in range(a.attempts):
        with heavy.hold(f"music {Path(a.out).stem}", log=lambda s: print(s, flush=True)) as waited:
            deadline += waited      # the time spent waiting for the drawn images (phase D) is not the takes' time
            raw = take_one(a, tmp, log, k, deadline, need)
        if isinstance(raw, Path):
            return raw
        if raw is None:
            return None
        need = raw
    log.setdefault("fallback_reason", f"all {a.attempts} ACE-Step takes rejected")
    return None


def take_one(a, tmp, log, k, deadline, need):
    """one ACE-Step take and its vocals check, holding the heavy-model lock -> the clean take's path, None to stop (the
    code-made bed is used), or the time the next take needs (this one was rejected)"""
    seed = a.seed + k
    left = deadline - time.time()
    if left < need:     # don't start a take that can't finish in time (need = the last take's time + 10 %)
        log["fallback_reason"] = (f"time limit of {a.max_minutes} min: {left / 60:.1f} min left, "
                                  f"a take needs about {need / 60:.1f} min")
        return None
    raw = tmp / f"ace_take{k + 1}_seed{seed}.wav"
    take = {"take": k + 1, "seed": seed}
    log["takes"].append(take)
    t0 = time.time()
    rc, out, err = run_limited([ACE_PY, "-m", "monteer.music.ace_gen", "--seconds", a.seconds + 1.0, "--steps", a.steps,
                                "--seed", seed, "--prompt", a.prompt, "--out", raw], left, env=ace_env())
    take["generate_s"] = round(time.time() - t0, 1)
    need = take["generate_s"] * 1.1 + 90       # next take: same length, plus the vocals check
    if rc is None:
        take["result"] = f"stopped: over the {a.max_minutes} min limit"
        log["fallback_reason"] = take["result"]
        return None
    if rc != 0 or not raw.exists():
        take["result"] = "failed: " + (err.strip().splitlines() or ["no output"])[-1][:300]
        log["fallback_reason"] = "ACE-Step failed"
        return None
    take.update(last_json(out) or {})
    lufs, peak, dur = measure(raw)
    if dur < a.seconds or lufs < -45:
        take["result"] = f"rejected: broken file (length {dur:.1f} s, loudness {lufs} LUFS)"
        return need
    t1 = time.time()
    rc, out, err = run_limited([ACE_PY, "-m", "monteer.music.vocal_check", raw], 900, env=ace_env())
    chk = last_json(out) if rc == 0 else None
    take["check_s"] = round(time.time() - t1, 1)
    if chk is None:
        take["result"] = "rejected: the vocals check could not run: " + (err.strip().splitlines() or ["?"])[-1][:300]
        return need
    take["vocal_check"] = {k2: chk[k2] for k2 in ("vocals", "reasons", "voice_score", "top_voice_labels", "words")}
    if chk["vocals"]:
        take["result"] = "rejected: " + "; ".join(chk["reasons"])
        return need
    take["result"] = "accepted"
    return raw


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seconds", type=float, required=True, help="length of the bed")
    ap.add_argument("--out", required=True, help="output .wav (a .json report is written next to it)")
    ap.add_argument("--prompt", default=DEFAULT_PROMPT, help="ACE-Step style prompt (default: dark/tense documentary)")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--steps", type=int, default=27, help="ACE-Step steps (27 = fast setting, 60 = default)")
    ap.add_argument("--attempts", type=int, default=2, help="ACE-Step takes to try when a take has vocals")
    ap.add_argument("--max-minutes", type=float, default=25.0, help="time limit for all ACE-Step takes together")
    ap.add_argument("--code-only", action="store_true", help="skip ACE-Step, use the code-generated bed")
    a = ap.parse_args()
    out = Path(a.out).resolve()
    if out.exists():
        sys.exit(f"{out} exists; music beds are never overwritten, choose a new name")
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.parent / (out.stem + "_takes")
    tmp.mkdir(exist_ok=True)
    t0 = time.time()
    log = {"seconds": a.seconds, "prompt": a.prompt, "steps": a.steps, "seed": a.seed, "attempts": a.attempts,
           "max_minutes": a.max_minutes, "takes": []}
    raw = None
    if a.code_only:
        log["fallback_reason"] = "--code-only"
    else:
        raw = try_ace(a, tmp, log)
    if raw is not None:
        log["generator"] = "ace-step"
    else:
        log["generator"] = "code-bed"
        raw = tmp / f"code_bed_seed{a.seed}.wav"
        t1 = time.time()
        r = subprocess.run([sys.executable, "-m", "monteer.music.code_bed", "--seconds", str(a.seconds), "--seed", str(a.seed),
                            "--out", str(raw)], capture_output=True, text=True, check=True, env=dict(os.environ, PYTHONPATH=str(ENGINE)))
        log["code_bed"] = dict(last_json(r.stdout) or {}, wall_s=round(time.time() - t1, 1))
    log["finish"] = finish(raw, out, a.seconds)
    log["licence"] = LICENCE[log["generator"]]
    log["total_s"] = round(time.time() - t0, 1)
    log["file"] = str(out)
    log["takes_folder"] = str(tmp)
    save_json(out.with_suffix(".json"), log)
    print(json.dumps({"generator": log["generator"], "fallback_reason": log.get("fallback_reason"),
                      "total_s": log["total_s"], "file": log["file"]}, ensure_ascii=False))


if __name__ == "__main__":
    main()
